import { useCallback, useEffect, useId, useMemo, useRef, useState } from "react";
import {
  GRPC_STATUS_CODES,
  grpcMockAddress,
  grpcurlListCommand,
  newGrpcMockMethod,
  updateGrpcMockConfig,
} from "../../commands/grpcMock";
import type { MessageKey } from "../../i18n";
import { Trans, useT } from "../../i18n/react";
import { isCancelled, toAppError } from "../../lib/errors";
import {
  describeProto,
  diagnosticLocation,
  exampleMessage,
  messageInput,
  methodKindLabel,
  pickImportPath,
  pickProtoFiles,
  setupKey,
  type DescribeResultDTO,
  type MethodDTO,
  type ProtoSetup,
} from "../../lib/grpc";
import { useStores, type GrpcBidiMode, type GrpcMockConfig, type GrpcMockMethod, type LocalServer, type MockHeader } from "../../stores";
import { FileAccessNotice, useFileAccessCheck } from "../common/FileAccessNotice";
import { GrpcMessageEditor } from "../editor/GrpcMessageEditor";
import styles from "./GrpcMock.module.css";
import hookStyles from "./Webhook.module.css";
import wsStyles from "./WsServer.module.css";

/** How long edits must pause before they are sent, in ms. */
export const GRPC_MOCK_CONFIG_DELAY_MS = 400;

const DEFAULT_CONFIG: GrpcMockConfig = { files: [], importPaths: [], reflection: true, methods: [] };

const BIDI_MODES: readonly { value: GrpcBidiMode; labelKey: MessageKey }[] = [
  { value: "each", labelKey: "servers.grpc.bidi.each" },
  { value: "stream", labelKey: "servers.grpc.bidi.stream" },
  { value: "echo", labelKey: "servers.grpc.bidi.echo" },
];

function errorText(err: unknown): string {
  const e = toAppError(err);
  return e.hint ? `${e.message} ${e.hint}` : e.message;
}

function methodKey(service: string, method: string): string {
  return `${service}/${method}`;
}

/** Whether a method of this kind sends several response messages. */
function streamsToClient(kind: string): boolean {
  return kind === "server_stream" || kind === "bidi";
}

/**
 * The Methods tab of a gRPC mock server (SSRV-07): the .proto files it
 * serves (chosen with the native dialog, stored like a gRPC request's:
 * relative to the project), whether it serves server reflection, the
 * methods the files define with whether each has a canned response, and
 * the selected method's response: the messages as JSON of its output type
 * (checked, completed and generated by the gRPC service), the status with
 * its message, headers, trailers, delay, and for streams the interval and
 * the bidirectional mode. A method without a response answers
 * UNIMPLEMENTED. Edits reach Go once typing pauses; a running server links
 * the files again and answers with the new responses at once.
 */
export function GrpcMockMethodsPanel({ server, readOnly = false }: { server: LocalServer; readOnly?: boolean }) {
  const t = useT();
  const stores = useStores();
  const [draft, setDraft] = useState<GrpcMockConfig>(() => server.grpcMock ?? DEFAULT_CONFIG);
  const [problem, setProblem] = useState<string | null>(null);
  const [described, setDescribed] = useState<DescribeResultDTO | null>(null);
  const [describeError, setDescribeError] = useState<string | null>(null);
  const [selected, setSelected] = useState<string | null>(null);
  const [status, setStatus] = useState<string | null>(null);
  // Files and import paths outside the allowed directories are refused
  // when the server starts (PRV-10).
  const access = useFileAccessCheck();

  const pending = useRef<GrpcMockConfig | null>(null);
  const seq = useRef(0);
  const flush = useCallback(() => {
    const config = pending.current;
    if (config === null) return;
    pending.current = null;
    const mine = ++seq.current;
    updateGrpcMockConfig(stores, server.id, config).then(
      () => {
        if (mine === seq.current) setProblem(null);
      },
      (err: unknown) => {
        if (mine === seq.current) setProblem(errorText(err));
      },
    );
  }, [stores, server.id]);

  const edit = useCallback((next: GrpcMockConfig) => {
    setDraft(next);
    pending.current = next;
  }, []);

  useEffect(() => {
    if (pending.current === null) return;
    const timer = setTimeout(flush, GRPC_MOCK_CONFIG_DELAY_MS);
    return () => clearTimeout(timer);
  }, [draft, flush]);
  // Edits still waiting are sent when the tab closes.
  useEffect(() => flush, [flush]);

  // The methods of the files, from the gRPC service (the linker and its cache).
  const setup: ProtoSetup = useMemo(() => ({ files: draft.files, importPaths: draft.importPaths }), [draft.files, draft.importPaths]);
  const key = setupKey(setup);
  const [reloads, setReloads] = useState(0);
  useEffect(() => {
    if (setup.files.length === 0) {
      setDescribed(null);
      setDescribeError(null);
      return;
    }
    const call = describeProto(setup, reloads > 0);
    call.then(
      (result) => {
        setDescribed(result);
        setDescribeError(null);
      },
      (err: unknown) => {
        if (!isCancelled(err)) setDescribeError(errorText(err));
      },
    );
    return () => void call.cancel?.();
    // `key` stands for the setup, which is a new object on every draft.
  }, [key, reloads]);

  const services = described?.services ?? [];
  const known = new Set(services.flatMap((s) => (s.methods ?? []).map((m) => methodKey(s.fullName, m.name))));
  const byKey = new Map(draft.methods.map((m, i) => [methodKey(m.service, m.method), i] as const));
  const orphans = draft.methods.filter((m) => described !== null && !known.has(methodKey(m.service, m.method)));
  const errors = (described?.diagnostics ?? []).filter((d) => d.severity === "error");

  const addFiles = async () => {
    setStatus(null);
    try {
      const picked = await pickProtoFiles();
      const files = [...draft.files, ...picked.filter((p) => !draft.files.includes(p))];
      if (files.length !== draft.files.length) edit({ ...draft, files });
      access.check(picked);
    } catch (err) {
      if (!isCancelled(err)) setStatus(errorText(err));
    }
  };
  const addImportPath = async () => {
    setStatus(null);
    try {
      const picked = await pickImportPath();
      if (picked !== "" && !draft.importPaths.includes(picked)) edit({ ...draft, importPaths: [...draft.importPaths, picked] });
      access.check(picked);
    } catch (err) {
      if (!isCancelled(err)) setStatus(errorText(err));
    }
  };

  const address = grpcMockAddress(server);
  const selectedMethod = (() => {
    if (selected === null) return null;
    for (const s of services) {
      const m = (s.methods ?? []).find((x) => methodKey(s.fullName, x.name) === selected);
      if (m !== undefined) return { service: s.fullName, method: m };
    }
    return null;
  })();

  return (
    <div className={wsStyles.settings}>
      <p className={wsStyles.connectNote}>
        {address === null ? (
          t("servers.grpc.startToCall")
        ) : draft.reflection ? (
          <Trans
            k="servers.grpc.callOrList"
            values={{
              address: <code className={wsStyles.url}>{address}</code>,
              command: <code className={wsStyles.url}>{grpcurlListCommand(server, address)}</code>,
            }}
          />
        ) : (
          <Trans k="servers.grpc.call" values={{ address: <code className={wsStyles.url}>{address}</code> }} />
        )}
      </p>

      <h3 className={wsStyles.sectionTitle}>{t("servers.grpc.files")}</h3>
      {draft.files.length === 0 ? (
        <p className={styles.empty}>{t("servers.grpc.noFiles")}</p>
      ) : (
        <ul className={styles.pathList} aria-label={t("servers.grpc.files")}>
          {draft.files.map((f) => (
            <li key={f} className={styles.pathRow}>
              <span className={styles.path} title={f}>
                {f}
              </span>
              <button
                type="button"
                className={`${wsStyles.button} ${wsStyles.danger}`}
                aria-label={t("servers.grpc.removeFile", { file: f })}
                disabled={readOnly}
                onClick={() => edit({ ...draft, files: draft.files.filter((x) => x !== f) })}
              >
                {t("servers.grpc.remove")}
              </button>
            </li>
          ))}
        </ul>
      )}
      {draft.importPaths.length > 0 && (
        <ul className={styles.pathList} aria-label={t("servers.grpc.importPaths")}>
          {draft.importPaths.map((p) => (
            <li key={p} className={styles.pathRow}>
              <span className={styles.path} title={p}>
                {t("servers.grpc.importPath", { path: p })}
              </span>
              <button
                type="button"
                className={`${wsStyles.button} ${wsStyles.danger}`}
                aria-label={t("servers.grpc.removeImportPath", { path: p })}
                disabled={readOnly}
                onClick={() => edit({ ...draft, importPaths: draft.importPaths.filter((x) => x !== p) })}
              >
                {t("servers.grpc.remove")}
              </button>
            </li>
          ))}
        </ul>
      )}
      <div className={wsStyles.settingRow}>
        <button type="button" className={wsStyles.button} disabled={readOnly} onClick={() => void addFiles()}>
          {t("servers.grpc.addFiles")}
        </button>
        <button type="button" className={wsStyles.button} disabled={readOnly} onClick={() => void addImportPath()}>
          {t("servers.grpc.addImportPath")}
        </button>
        <button
          type="button"
          className={wsStyles.button}
          disabled={draft.files.length === 0}
          title={t("servers.grpc.reloadTitle")}
          onClick={() => setReloads((n) => n + 1)}
        >
          {t("servers.grpc.reload")}
        </button>
      </div>
      <FileAccessNotice access={access} />
      <label className={wsStyles.check}>
        <input
          type="checkbox"
          checked={draft.reflection}
          disabled={readOnly}
          onChange={(e) => edit({ ...draft, reflection: e.target.checked })}
        />
        {t("servers.grpc.reflection")}
      </label>
      {status !== null && (
        <p className={wsStyles.error} role="alert">
          {status}
        </p>
      )}
      {describeError !== null && (
        <p className={wsStyles.error} role="alert">
          {describeError}
        </p>
      )}
      {errors.length > 0 && (
        <ul className={styles.diagnostics} aria-label={t("servers.grpc.problems")}>
          {errors.slice(0, 10).map((d, i) => (
            <li key={i}>
              <code>{diagnosticLocation(d)}</code> {d.message}
            </li>
          ))}
        </ul>
      )}

      <h3 className={wsStyles.sectionTitle}>{t("servers.tab.methods")}</h3>
      {services.length === 0 ? (
        <p className={styles.empty}>{draft.files.length === 0 ? t("servers.grpc.addFilesFirst") : t("servers.grpc.noServices")}</p>
      ) : (
        services.map((s) => (
          <div key={s.fullName}>
            <p className={styles.service}>{s.fullName}</p>
            <ul className={wsStyles.list} aria-label={t("servers.grpc.methodsOf", { service: s.fullName })}>
              {(s.methods ?? []).map((m) => {
                const k = methodKey(s.fullName, m.name);
                const mocked = byKey.has(k);
                return (
                  <li key={k} className={wsStyles.row} data-selected={selected === k || undefined}>
                    <div className={wsStyles.rowLine}>
                      <button
                        type="button"
                        className={wsStyles.rowMain}
                        aria-pressed={selected === k}
                        aria-label={t("servers.grpc.method", { name: m.name })}
                        onClick={() => setSelected(selected === k ? null : k)}
                      >
                        <span className={wsStyles.clientName}>{m.name}</span>
                        <span className={styles.kind}>{methodKindLabel(m.kind)}</span>
                        <span className={wsStyles.clientDetails}>→ {m.outputType}</span>
                      </button>
                      <span className={mocked ? styles.mocked : styles.unmocked}>{mocked ? t("servers.grpc.canned") : "UNIMPLEMENTED"}</span>
                    </div>
                  </li>
                );
              })}
            </ul>
          </div>
        ))
      )}
      {orphans.length > 0 && (
        <>
          <p className={styles.empty}>{t("servers.grpc.orphans")}</p>
          <ul className={styles.pathList} aria-label={t("servers.grpc.orphansLabel")}>
            {orphans.map((m) => (
              <li key={methodKey(m.service, m.method)} className={styles.pathRow}>
                <span className={styles.path}>
                  {m.service}/{m.method}
                </span>
                <button
                  type="button"
                  className={`${wsStyles.button} ${wsStyles.danger}`}
                  disabled={readOnly}
                  onClick={() => edit({ ...draft, methods: draft.methods.filter((x) => x !== m) })}
                >
                  {t("servers.grpc.remove")}
                </button>
              </li>
            ))}
          </ul>
        </>
      )}

      {selectedMethod !== null && (
        <MethodEditor
          key={methodKey(selectedMethod.service, selectedMethod.method.name)}
          setup={setup}
          service={selectedMethod.service}
          method={selectedMethod.method}
          config={(() => {
            const i = byKey.get(methodKey(selectedMethod.service, selectedMethod.method.name));
            return i === undefined ? null : draft.methods[i];
          })()}
          readOnly={readOnly}
          onChange={(next) => {
            const k = methodKey(selectedMethod.service, selectedMethod.method.name);
            const i = byKey.get(k);
            let methods: GrpcMockMethod[];
            if (next === null) methods = draft.methods.filter((_, j) => j !== i);
            else if (i === undefined) methods = [...draft.methods, next];
            else methods = draft.methods.map((m, j) => (j === i ? next : m));
            edit({ ...draft, methods });
          }}
        />
      )}

      {problem !== null && (
        <p className={wsStyles.error} role="alert">
          {problem}
        </p>
      )}
      <p className={wsStyles.help}>{t("servers.grpc.help")}</p>
    </div>
  );
}

/** The canned response of one method, or Mock this method when it has none. */
function MethodEditor({
  setup,
  service,
  method,
  config,
  readOnly,
  onChange,
}: {
  setup: ProtoSetup;
  service: string;
  method: MethodDTO;
  config: GrpcMockMethod | null;
  readOnly: boolean;
  onChange: (next: GrpcMockMethod | null) => void;
}) {
  const t = useT();
  const baseId = useId();
  const [busy, setBusy] = useState(false);
  const [failure, setFailure] = useState<string | null>(null);
  const streams = streamsToClient(method.kind);
  const title = `${service}/${method.name}`;

  const mock = async () => {
    setBusy(true);
    setFailure(null);
    let example: string | null = null;
    try {
      example = (await exampleMessage(messageInput(setup, service, method.name, "", true))).json;
    } catch (err) {
      if (!isCancelled(err)) setFailure(errorText(err));
    }
    setBusy(false);
    onChange(newGrpcMockMethod(service, method.name, example));
  };

  if (config === null) {
    return (
      <section className={styles.editor} aria-label={t("servers.grpc.responseOf", { name: method.name })}>
        <p className={styles.editorTitle}>{title}</p>
        <p className={styles.empty}>{t("servers.grpc.noCanned")}</p>
        <div>
          <button type="button" className={wsStyles.button} disabled={readOnly || busy} onClick={() => void mock()}>
            {t("servers.grpc.mockMethod")}
          </button>
        </div>
        {failure !== null && (
          <p className={wsStyles.error} role="alert">
            {failure}
          </p>
        )}
      </section>
    );
  }

  const set = (patch: Partial<GrpcMockMethod>) => onChange({ ...config, ...patch });
  const number = (text: string) => {
    const n = Number(text.trim() === "" ? "0" : text);
    return Number.isInteger(n) && n >= 0 ? n : null;
  };
  const target = { service, method: method.name, inputType: method.outputType };
  const messages = streams ? config.messages : config.messages.slice(0, 1);
  const shown = messages.length === 0 && !streams ? [""] : messages;
  const setMessage = (i: number, text: string) => {
    const next = [...config.messages];
    while (next.length <= i) next.push("");
    next[i] = text;
    set({ messages: next });
  };

  return (
    <section className={styles.editor} aria-label={t("servers.grpc.responseOf", { name: method.name })}>
      <p className={styles.editorTitle}>{title}</p>
      <div className={wsStyles.settingRow}>
        <label className={wsStyles.settingLabel} htmlFor={`${baseId}-status`}>
          {t("servers.grpc.status")}
        </label>
        <select
          id={`${baseId}-status`}
          className={wsStyles.input}
          value={config.status}
          disabled={readOnly}
          onChange={(e) => set({ status: Number(e.target.value) })}
        >
          {GRPC_STATUS_CODES.map((c) => (
            <option key={c.code} value={c.code}>
              {c.code} {c.name}
            </option>
          ))}
        </select>
        {config.status !== 0 && (
          <input
            className={`${wsStyles.input} ${styles.statusMessage}`}
            aria-label={t("servers.grpc.statusMessage")}
            placeholder={t("servers.grpc.statusMessage")}
            value={config.statusMessage}
            disabled={readOnly}
            spellCheck={false}
            onChange={(e) => set({ statusMessage: e.target.value })}
          />
        )}
      </div>
      <div className={wsStyles.settingRow}>
        <label className={wsStyles.settingLabel} htmlFor={`${baseId}-delay`}>
          {t("servers.grpc.delay")}
        </label>
        <input
          id={`${baseId}-delay`}
          className={`${wsStyles.input} ${wsStyles.sizeInput}`}
          inputMode="numeric"
          value={String(config.delayMs)}
          disabled={readOnly}
          onChange={(e) => {
            const n = number(e.target.value);
            if (n !== null) set({ delayMs: n });
          }}
        />
        {streams && (
          <>
            <label className={wsStyles.settingLabel} htmlFor={`${baseId}-interval`}>
              {t("servers.grpc.interval")}
            </label>
            <input
              id={`${baseId}-interval`}
              className={`${wsStyles.input} ${wsStyles.sizeInput}`}
              inputMode="numeric"
              value={String(config.intervalMs)}
              disabled={readOnly}
              onChange={(e) => {
                const n = number(e.target.value);
                if (n !== null) set({ intervalMs: n });
              }}
            />
          </>
        )}
      </div>
      {method.kind === "bidi" && (
        <div className={wsStyles.settingRow}>
          <label className={wsStyles.settingLabel} htmlFor={`${baseId}-bidi`}>
            {t("servers.grpc.answer")}
          </label>
          <select
            id={`${baseId}-bidi`}
            className={wsStyles.input}
            value={config.bidi}
            disabled={readOnly}
            onChange={(e) => set({ bidi: e.target.value as GrpcBidiMode })}
          >
            {BIDI_MODES.map((m) => (
              <option key={m.value} value={m.value}>
                {t(m.labelKey)}
              </option>
            ))}
          </select>
        </div>
      )}
      {!(method.kind === "bidi" && config.bidi === "echo") &&
        shown.map((text, i) => (
          <div key={i} className={styles.message}>
            <div className={styles.messageHeader}>
              <span>{streams ? t("servers.grpc.message", { n: i + 1 }) : t("servers.grpc.responseMessage")}</span>
              {streams && (
                <button
                  type="button"
                  className={`${wsStyles.button} ${wsStyles.danger}`}
                  aria-label={t("servers.grpc.removeMessage", { n: i + 1 })}
                  disabled={readOnly}
                  onClick={() => set({ messages: config.messages.filter((_, j) => j !== i) })}
                >
                  {t("servers.grpc.remove")}
                </button>
              )}
            </div>
            <div className={styles.messageFrame}>
              <GrpcMessageEditor
                message={text}
                setup={setup}
                target={target}
                readOnly={readOnly}
                output
                ariaLabel={streams ? t("servers.grpc.message", { n: i + 1 }) : t("servers.grpc.responseMessage")}
                onChange={(text) => setMessage(i, text)}
              />
            </div>
          </div>
        ))}
      {streams && config.bidi !== "echo" && (
        <div>
          <button
            type="button"
            className={wsStyles.button}
            disabled={readOnly}
            onClick={() => set({ messages: [...config.messages, config.messages[config.messages.length - 1] ?? "{}"] })}
          >
            {t("servers.grpc.addMessage")}
          </button>
        </div>
      )}
      <MetadataRows kind="headers" rows={config.headers} readOnly={readOnly} onChange={(headers) => set({ headers })} />
      <MetadataRows kind="trailers" rows={config.trailers} readOnly={readOnly} onChange={(trailers) => set({ trailers })} />
      <div>
        <button type="button" className={`${wsStyles.button} ${wsStyles.danger}`} disabled={readOnly} onClick={() => onChange(null)}>
          {t("servers.grpc.removeCanned")}
        </button>
      </div>
    </section>
  );
}

/** Response metadata rows (headers or trailers); values of -bin keys are Base64. */
function MetadataRows({
  kind,
  rows,
  readOnly,
  onChange,
}: {
  kind: "headers" | "trailers";
  rows: readonly MockHeader[];
  readOnly: boolean;
  onChange: (rows: MockHeader[]) => void;
}) {
  const t = useT();
  const headers = kind === "headers";
  const label = headers ? t("servers.grpc.headers") : t("servers.grpc.trailers");
  const editRow = (i: number, patch: Partial<MockHeader>) => onChange(rows.map((r, j) => (j === i ? { ...r, ...patch } : r)));
  return (
    <div className={hookStyles.headerRows} role="group" aria-label={label}>
      <span className={wsStyles.settingLabel}>{label}</span>
      {rows.map((r, i) => (
        <div key={i} className={hookStyles.headerRow}>
          <input
            type="checkbox"
            aria-label={headers ? t("servers.grpc.sendHeader", { n: i + 1 }) : t("servers.grpc.sendTrailer", { n: i + 1 })}
            checked={r.enabled}
            disabled={readOnly}
            onChange={(e) => editRow(i, { enabled: e.target.checked })}
          />
          <input
            className={`${wsStyles.input} ${hookStyles.headerName}`}
            aria-label={headers ? t("servers.grpc.headerName", { n: i + 1 }) : t("servers.grpc.trailerName", { n: i + 1 })}
            placeholder={t("servers.grpc.keyPlaceholder")}
            value={r.name}
            disabled={readOnly}
            spellCheck={false}
            autoComplete="off"
            onChange={(e) => editRow(i, { name: e.target.value })}
          />
          <input
            className={`${wsStyles.input} ${hookStyles.headerValue}`}
            aria-label={headers ? t("servers.grpc.headerValue", { n: i + 1 }) : t("servers.grpc.trailerValue", { n: i + 1 })}
            placeholder={r.name.toLowerCase().endsWith("-bin") ? "Base64" : t("servers.grpc.valuePlaceholder")}
            value={r.value}
            disabled={readOnly}
            spellCheck={false}
            autoComplete="off"
            onChange={(e) => editRow(i, { value: e.target.value })}
          />
          <button
            type="button"
            className={`${wsStyles.button} ${wsStyles.danger}`}
            aria-label={headers ? t("servers.grpc.removeHeader", { n: i + 1 }) : t("servers.grpc.removeTrailer", { n: i + 1 })}
            disabled={readOnly}
            onClick={() => onChange(rows.filter((_, j) => j !== i))}
          >
            {t("servers.grpc.remove")}
          </button>
        </div>
      ))}
      <div>
        <button
          type="button"
          className={wsStyles.button}
          disabled={readOnly}
          onClick={() => onChange([...rows, { enabled: true, name: "", value: "" }])}
        >
          {headers ? t("servers.grpc.addHeader") : t("servers.grpc.addTrailer")}
        </button>
      </div>
    </div>
  );
}
