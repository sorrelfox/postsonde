// Local TLS (SRV-05): the TLS part of the server editors. A server serves
// plain text, TLS with a certificate generated by PostSonde's local CA,
// or TLS with the user's certificate files (PEM certificate and key, or
// PKCS#12). Only paths reach the definition; a passphrase goes to Go's
// local secret storage. See docs/servers.md (TLS).

/** What the TLS fields edit. */
export interface TlsDraft {
  enabled: boolean;
  certificate: "generated" | "files";
  /** Which kind of files: PEM certificate and key, or one PKCS#12 file. */
  source: "pem" | "pkcs12";
  certFile: string;
  keyFile: string;
  pfxFile: string;
  /** The passphrase typed; only sent when `passphraseTouched`. */
  passphrase: string;
  passphraseTouched: boolean;
}

/** The draft of a server's TLS (off for null). */
export function tlsDraftOf(tls: ServerTls | null): TlsDraft {
  return {
    enabled: tls !== null,
    certificate: tls?.certificate ?? "generated",
    source: tls !== null && tls.pfxFile !== "" ? "pkcs12" : "pem",
    certFile: tls?.certFile ?? "",
    keyFile: tls?.keyFile ?? "",
    pfxFile: tls?.pfxFile ?? "",
    passphrase: "",
    passphraseTouched: false,
  };
}

/** The TLS input of a draft; null serves plain text. */
export function tlsInputOf(d: TlsDraft): ServerTlsInput | null {
  if (!d.enabled) return null;
  if (d.certificate === "generated") {
    return { certificate: "generated", certFile: "", keyFile: "", pfxFile: "", passphrase: null };
  }
  const pem = d.source === "pem";
  return {
    certificate: "files",
    certFile: pem ? d.certFile.trim() : "",
    keyFile: pem ? d.keyFile.trim() : "",
    pfxFile: pem ? "" : d.pfxFile.trim(),
    passphrase: d.passphraseTouched ? d.passphrase : null,
  };
}

/** Whether the draft would change the server's TLS. */
export function tlsDraftChanged(d: TlsDraft, tls: ServerTls | null): boolean {
  const a = tlsInputOf(d);
  const b = keepTls(tls);
  if (a === null || b === null) return a !== b;
  return (
    a.certificate !== b.certificate ||
    a.certFile !== b.certFile ||
    a.keyFile !== b.keyFile ||
    a.pfxFile !== b.pfxFile ||
    a.passphrase !== null
  );
}

/** What TLS makes of a kind of server: HTTPS, wss, or TLS (over TCP, or gRPC over h2). */
export function tlsProtocolLabel(type: string): string {
  if (type === WEBSOCKET_TYPE) return "wss";
  if (type === TCP_TYPE || type === GRPC_MOCK_TYPE) return "TLS";
  return "HTTPS";
}

/** A short description of a server's TLS, for the details. */
export function describeTls(tls: ServerTls | null): string {
  if (tls === null) return translate("servers.tls.describe.off");
  if (tls.certificate === "generated") return translate("servers.tls.describe.generated");
  return tls.pfxFile !== ""
    ? translate("servers.tls.describe.pfx", { file: tls.pfxFile })
    : translate("servers.tls.describe.cert", { file: tls.certFile });
}

export interface TlsFieldsProps {
  /** The kind of server, for the label (HTTPS, wss, TLS). */
  serverType: string;
  draft: TlsDraft;
  onChange: (d: TlsDraft) => void;
  disabled: boolean;
  /** A passphrase is stored for the files the server has now. */
  hasPassphrase: boolean;
  /** Distinguishes the radio groups of several editors on one screen. */
  idPrefix: string;
}

/** The TLS fields: on or off, the kind of certificate, the files and the passphrase, and the local CA. */
export function TlsFields({ serverType, draft, onChange, disabled, hasPassphrase, idPrefix }: TlsFieldsProps) {
  const t = useT();
  const [pickError, setPickError] = useState<string | null>(null);
  // Certificate files outside the allowed directories are refused (PRV-10).
  const access = useFileAccessCheck();
  const set = (patch: Partial<TlsDraft>) => onChange({ ...draft, ...patch });
  const pick = (kind: TlsFileKind) => {
    setPickError(null);
    pickTlsFile(kind).then(
      (path) => {
        if (path === "") return;
        if (kind === "cert") set({ certFile: path });
        else if (kind === "key") set({ keyFile: path });
        else set({ pfxFile: path });
        access.check(path);
      },
      (err: unknown) => setPickError(toAppError(err).message),
    );
  };
  const protocol = tlsProtocolLabel(serverType);

  return (
    <div className={tlsStyles.tls}>
      <label className={styles.check}>
        <input type="checkbox" checked={draft.enabled} disabled={disabled} onChange={(e) => set({ enabled: e.target.checked })} />
        <span>{t("servers.tls.serve", { protocol })}</span>
      </label>
      {draft.enabled && (
        <>
          <div className={styles.typeChoice} role="radiogroup" aria-label={t("servers.tls.certificate")}>
            <label className={styles.typeOption}>
              <input
                type="radio"
                name={`${idPrefix}-tls-certificate`}
                checked={draft.certificate === "generated"}
                disabled={disabled}
                onChange={() => set({ certificate: "generated" })}
              />
              {t("servers.tls.generated")}
            </label>
            <label className={styles.typeOption}>
              <input
                type="radio"
                name={`${idPrefix}-tls-certificate`}
                checked={draft.certificate === "files"}
                disabled={disabled}
                onChange={() => set({ certificate: "files" })}
              />
              {t("servers.tls.mine")}
            </label>
          </div>
          {draft.certificate === "generated" ? (
            <LocalCAPanel />
          ) : (
            <>
              <div className={styles.typeChoice} role="radiogroup" aria-label={t("servers.tls.files")}>
                <label className={styles.typeOption}>
                  <input
                    type="radio"
                    name={`${idPrefix}-tls-source`}
                    checked={draft.source === "pem"}
                    disabled={disabled}
                    onChange={() => set({ source: "pem" })}
                  />
                  {t("servers.tls.pem")}
                </label>
                <label className={styles.typeOption}>
                  <input
                    type="radio"
                    name={`${idPrefix}-tls-source`}
                    checked={draft.source === "pkcs12"}
                    disabled={disabled}
                    onChange={() => set({ source: "pkcs12" })}
                  />
                  {t("servers.tls.pkcs12")}
                </label>
              </div>
              {draft.source === "pem" ? (
                <>
                  <FileField label={t("servers.tls.certificate")} value={draft.certFile} disabled={disabled} onChange={(v) => set({ certFile: v })} onPick={() => pick("cert")} />
                  <FileField
                    label={t("servers.tls.privateKey")}
                    value={draft.keyFile}
                    placeholder={t("servers.tls.keyInCert")}
                    disabled={disabled}
                    onChange={(v) => set({ keyFile: v })}
                    onPick={() => pick("key")}
                  />
                </>
              ) : (
                <FileField label={t("servers.tls.pfxFile")} value={draft.pfxFile} disabled={disabled} onChange={(v) => set({ pfxFile: v })} onPick={() => pick("pfx")} />
              )}
              <label className={styles.field}>
                <span>{t("servers.tls.passphrase")}</span>
                <input
                  className={styles.input}
                  type="password"
                  value={draft.passphrase}
                  placeholder={hasPassphrase && !draft.passphraseTouched ? t("servers.tls.passphraseStored") : t("servers.tls.passphraseNone")}
                  autoComplete="off"
                  disabled={disabled}
                  onChange={(e) => set({ passphrase: e.target.value, passphraseTouched: true })}
                />
              </label>
              <p className={styles.formNote}>
                {t("servers.tls.filesNote")}
              </p>
              <FileAccessNotice access={access} />
            </>
          )}
          {pickError !== null && (
            <p className={styles.error} role="alert">
              {pickError}
            </p>
          )}
        </>
      )}
    </div>
  );
}

function FileField({
  label,
  value,
  placeholder,
  disabled,
  onChange,
  onPick,
}: {
  label: string;
  value: string;
  placeholder?: string;
  disabled: boolean;
  onChange: (v: string) => void;
  onPick: () => void;
}) {
  const t = useT();
  return (
    <div className={tlsStyles.fileRow}>
      <label className={styles.field}>
        <span>{label}</span>
        <input
          className={styles.input}
          value={value}
          placeholder={placeholder ?? t("servers.tls.pathPlaceholder")}
          spellCheck={false}
          autoComplete="off"
          disabled={disabled}
          onChange={(e) => onChange(e.target.value)}
        />
      </label>
      <button type="button" className={styles.smallButton} disabled={disabled} aria-label={t("servers.tls.chooseLabel", { label })} onClick={onPick}>
        {t("servers.tls.choose")}
      </button>
    </div>
  );
}

/**
 * The local CA that signs generated certificates: where ca.pem is, its
 * fingerprint, and whether PostSonde's own clients trust it, with a
 * button to trust it (Settings, Network, CA bundles). It is never
 * installed in the system: docs/servers.md says how to trust it elsewhere.
 */
export function LocalCAPanel() {
  const t = useT();
  const [ca, setCA] = useState<LocalCADTO | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    let live = true;
    getLocalCA().then(
      (dto) => {
        if (live) setCA(dto);
      },
      (err: unknown) => {
        if (live) setError(toAppError(err).message);
      },
    );
    return () => {
      live = false;
    };
  }, []);

  const trust = () => {
    if (ca === null) return;
    setError(null);
    trustCABundle(ca.path)
      .then(() => getLocalCA())
      .then(setCA, (err: unknown) => setError(toAppError(err).message));
  };
  const copyPath = () => {
    if (ca === null) return;
    copyText(ca.path).then(
      () => setCopied(true),
      (err: unknown) => console.warn(`servers: ${formatError(err)}`),
    );
  };

  return (
    <div className={tlsStyles.ca} aria-label={t("servers.ca.label")}>
      <p className={tlsStyles.caTitle}>
        <IconLock size={12} />
        <span>{t("servers.ca.about")}</span>
      </p>
      {ca !== null && (
        <>
          {ca.path !== "" && (
            <div className={tlsStyles.caRow}>
              <code className={tlsStyles.caPath} title={/* i18n-ignore: an algorithm name and a fingerprint */ `SHA-256 ${ca.sha256}`}>
                {ca.path}
              </code>
              <button type="button" className={styles.smallButton} onClick={copyPath}>
                {copied ? t("servers.ca.copied") : t("servers.ca.copyPath")}
              </button>
              <button
                type="button"
                className={styles.smallButton}
                onClick={() => revealLocalCA().catch((err: unknown) => setError(toAppError(err).message))}
              >
                {t("servers.ca.showFile")}
              </button>
            </div>
          )}
          {ca.trusted ? (
            <p className={styles.formNote}>{t("servers.ca.trusted")}</p>
          ) : (
            ca.path !== "" && (
              <div className={tlsStyles.caRow}>
                <button type="button" className={styles.smallButton} onClick={trust}>
                  {t("servers.ca.trust")}
                </button>
                <span className={styles.formNote}>{t("servers.ca.trustNote")}</span>
              </div>
            )
          )}
          <p className={styles.formNote}>{t("servers.ca.otherClients")}</p>
        </>
      )}
      {error !== null && (
        <p className={styles.error} role="alert">
          {error}
        </p>
      )}
    </div>
  );
}

/**
 * The TLS section of an existing server (the folder's Server tab and the
 * Servers view's details): the fields over a draft, applied with Apply.
 * TLS cannot change while the server holds its port.
 */
export function TlsSection({ server, readOnly }: { server: LocalServer; readOnly: boolean }) {
  const t = useT();
  const stores = useStores();
  const [draft, setDraft] = useState(() => tlsDraftOf(server.tls));
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const active = isServerActive(server.state);
  const locked = readOnly || active || busy;
  const dirty = tlsDraftChanged(draft, server.tls);

  // The server's TLS changed elsewhere (the folder file was edited and
  // synced, the other editor applied it): follow it, unless a change is
  // being edited here.
  const [seen, setSeen] = useState(server.tls);
  if (JSON.stringify(server.tls) !== JSON.stringify(seen)) {
    const wasClean = !tlsDraftChanged(draft, seen);
    setSeen(server.tls);
    if (wasClean) setDraft(tlsDraftOf(server.tls));
  }

  const apply = (next: TlsDraft) => {
    setBusy(true);
    setError(null);
    updateServerSettings(stores, server.id, {
      name: server.name === server.typeLabel ? "" : server.name,
      host: server.host === "" ? "localhost" : server.host,
      port: server.port,
      allowLan: server.allowLan,
      tls: tlsInputOf(next),
    }).then(
      (saved) => {
        setBusy(false);
        setDraft(tlsDraftOf(saved.tls));
      },
      (err: unknown) => {
        setBusy(false);
        const appErr = toAppError(err);
        setError(appErr.hint ? `${appErr.message} ${appErr.hint}` : appErr.message);
      },
    );
  };
  // Turning TLS off or on with the generated certificate needs no files:
  // it is saved at once, like the other settings.
  const onChange = (next: TlsDraft) => {
    setDraft(next);
    setError(null);
    const needsNoFiles = !next.enabled || next.certificate === "generated";
    const switched = next.enabled !== draft.enabled || next.certificate !== draft.certificate;
    if (switched && needsNoFiles && tlsDraftChanged(next, server.tls)) apply(next);
  };

  return (
    <section className={tlsStyles.section} aria-label="TLS">
      <TlsFields
        serverType={server.type}
        draft={draft}
        onChange={onChange}
        disabled={locked}
        hasPassphrase={server.tls?.hasPassphrase ?? false}
        idPrefix={`server-${server.id}`}
      />
      {dirty && !active && (
        <div className={styles.formButtons}>
          <button type="button" className={`${styles.smallButton} ${styles.primary}`} disabled={locked} onClick={() => apply(draft)}>
            {t("servers.tls.apply")}
          </button>
          <button
            type="button"
            className={styles.smallButton}
            disabled={busy}
            onClick={() => {
              setDraft(tlsDraftOf(server.tls));
              setError(null);
            }}
          >
            {t("servers.tls.revert")}
          </button>
        </div>
      )}
      {active && !readOnly && <p className={styles.formNote}>{t("servers.tls.stopToChange")}</p>}
      {error !== null && (
        <p className={styles.error} role="alert">
          {error}
        </p>
      )}
    </section>
  );
}
