// rc2Cipher is an RC2 key schedule: 64 16-bit words.
type rc2Cipher struct {
	k [64]uint16
}

// newRC2 expands a 1-128 byte key with an effective key length of
// effectiveBits (1-1024) bits (RFC 2268 section 2).
func newRC2(key []byte, effectiveBits int) (cipher.Block, error) {
	t := len(key)
	if t < 1 || t > 128 || effectiveBits < 1 || effectiveBits > 1024 {
		return nil, errors.New("pkcs12: invalid RC2 key size")
	}
	var l [128]byte
	copy(l[:], key)
	for i := t; i < 128; i++ {
		l[i] = piTable[l[i-1]+l[i-t]]
	}
	t8 := (effectiveBits + 7) / 8
	tm := byte(255 >> uint(8*t8-effectiveBits))
	l[128-t8] = piTable[l[128-t8]&tm]
	for i := 127 - t8; i >= 0; i-- {
		l[i] = piTable[l[i+1]^l[i+t8]]
	}
	c := &rc2Cipher{}
	for i := range c.k {
		c.k[i] = uint16(l[2*i]) | uint16(l[2*i+1])<<8
	}
	return c, nil
}

func (c *rc2Cipher) BlockSize() int { return rc2BlockSize }

// Encrypt is RFC 2268 section 3: five mixing rounds, a mashing round, six
// mixing rounds, a mashing round and five mixing rounds.
func (c *rc2Cipher) Encrypt(dst, src []byte) {
	r := [4]uint16{
		binary.LittleEndian.Uint16(src[0:]), binary.LittleEndian.Uint16(src[2:]),
		binary.LittleEndian.Uint16(src[4:]), binary.LittleEndian.Uint16(src[6:]),
	}
	j := 0
	mix := func() {
		for i, s := range [4]int{1, 2, 3, 5} {
			r[i] += c.k[j] + (r[(i+3)&3] & r[(i+2)&3]) + (^r[(i+3)&3] & r[(i+1)&3])
			r[i] = bits.RotateLeft16(r[i], s)
			j++
		}
	}
	mash := func() {
		for i := range r {
			r[i] += c.k[r[(i+3)&3]&63]
		}
	}
	for round := range 16 {
		mix()
		if round == 4 || round == 10 {
			mash()
		}
	}
	for i, w := range r {
		binary.LittleEndian.PutUint16(dst[2*i:], w)
	}
}

// Decrypt runs the rounds of Encrypt backwards (RFC 2268 section 4).
func (c *rc2Cipher) Decrypt(dst, src []byte) {
	r := [4]uint16{
		binary.LittleEndian.Uint16(src[0:]), binary.LittleEndian.Uint16(src[2:]),
		binary.LittleEndian.Uint16(src[4:]), binary.LittleEndian.Uint16(src[6:]),
	}
	j := 63
	rmix := func() {
		for i := 3; i >= 0; i-- {
			s := [4]int{1, 2, 3, 5}[i]
			r[i] = bits.RotateLeft16(r[i], -s)
			r[i] -= c.k[j] + (r[(i+3)&3] & r[(i+2)&3]) + (^r[(i+3)&3] & r[(i+1)&3])
			j--
		}
	}
	rmash := func() {
		for i := 3; i >= 0; i-- {
			r[i] -= c.k[r[(i+3)&3]&63]
		}
	}
	for round := range 16 {
		rmix()
		if round == 4 || round == 10 {
			rmash()
		}
	}
	for i, w := range r {
		binary.LittleEndian.PutUint16(dst[2*i:], w)
	}
}

// rc2ParamBits maps the rc2ParameterVersion of RC2-CBC parameters (RFC
// 8018 appendix B.2.3) to an effective key length in bits.
func rc2ParamBits(version int) (int, bool) {
	switch version {
	case 160:
		return 40, true
	case 120:
		return 64, true
	case 58:
		return 128, true
	}
	if version >= 256 && version <= 1024 {
		return version, true
	}
	return 0, false
}
